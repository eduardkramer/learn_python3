# 1. Maak een lijst met minimaal vijf bestemmingen
five_places = ['japan', 'indonesia', 'france', 'engeland', 'america']

# 2. Print de oorspronkelijke lijst
print(five_places)

# 3. Print de lijst alfabetisch met sorted()
print(sorted(five_places))

# 4. Print de oorspronkelijke lijst opnieuw
print(five_places)

# 5. Print de lijst in omgekeerd alfabetische volgorde
print(sorted(five_places, reverse=True))

# 6. Print de oorspronkelijke lijst opnieuw
print(five_places)

# 7. Verander de volgorde met reverse() en print de lijst
five_places.reverse()
print(five_places)

# 8. Herstel de oorspronkelijke volgorde met reverse() en print de lijst
five_places.reverse()
print(five_places)

# 9. Sorteer de lijst permanent alfabetisch met sort() en print de lijst
five_places.sort()
print(five_places)

# 10. Sorteer de lijst permanent omgekeerd alfabetisch met sort() en print de lijst
five_places.sort(reverse=True)
print(five_places)